"""
State Definition for Multi-Agent Deep Research System
Architecture Reference: docs/EXPLANATIONS.md - Section 2 and Chapter 13

First Principle:
State in an agent graph acts as the blackboard communication channel.
Agents read their necessary inputs and write back their localized findings.

Execution isolation (Chapter 13):
Every research run is created through ``new_run_state`` which builds brand-new
containers (no shared mutable defaults) and stamps a unique ``run_id``. Every
researcher record carries that ``run_id`` so downstream nodes can PROVE that
the evidence they consume belongs to the current run.
"""

import hashlib
import uuid
from datetime import datetime, timezone
from typing import Annotated, Any, Dict, List, Optional, TypedDict


def merge_dicts(left: Dict[str, Any], right: Dict[str, Any]) -> Dict[str, Any]:
    """Reducer function to merge dictionaries from concurrent agent nodes."""
    merged = dict(left or {})
    for key, value in (right or {}).items():
        if key in merged and isinstance(merged[key], list) and isinstance(value, list):
            merged[key] = merged[key] + value
        elif key in merged and isinstance(merged[key], dict) and isinstance(value, dict):
            merged[key] = merge_dicts(merged[key], value)
        elif key in merged and isinstance(merged[key], (int, float)) and isinstance(value, (int, float)) \
                and not isinstance(merged[key], bool) and not isinstance(value, bool):
            if key in ("search_count", "total_tokens", "prompt_tokens", "completion_tokens"):
                merged[key] = merged[key] + value
            else:
                merged[key] = value
        else:
            merged[key] = value
    return merged


def append_list(left: Any, right: Any) -> List[Any]:
    """Reducer: accumulate list items (dict items are appended, lists extended)."""
    res = list(left or [])
    if isinstance(right, list):
        res.extend(right)
    elif right is not None:
        res.append(right)
    return res


# Backward-compatible name used by earlier code
append_score_history = append_list


def stable_key(text: str, length: int = 6) -> str:
    """Deterministic short key (replaces hash(), which is salted per process and collision-prone)."""
    return hashlib.sha1((text or "").strip().encode("utf-8")).hexdigest()[:length]


def generate_run_id() -> str:
    """Globally unique, sortable run identifier."""
    return f"run_{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S')}_{uuid.uuid4().hex[:8]}"


class ResearchState(TypedDict, total=False):
    """
    Central shared state passed between all nodes in the LangGraph workflow.
    Supports Phase 1 baseline feed-forward and Phase 2 critic-revision loops.
    """
    # --- Identity / isolation ---
    run_id: str
    benchmark_id: str

    # The primary user query / topic
    question: str

    # The decomposed sub-questions generated by the planner
    plan: List[str]

    # Search results keyed by sub-question: {sub_question: [{title, url, snippet, provenance}, ...]}
    search_results: Annotated[Dict[str, List[Dict[str, str]]], merge_dicts]

    # Researcher findings keyed by sub-question
    notes: Annotated[Dict[str, List[str]], merge_dicts]

    # One provenance-tagged record per researcher execution (carries run_id)
    research_records: Annotated[List[Dict[str, Any]], append_list]

    # Output of the relevance-validation gate (overwritten, not merged)
    validated_notes: Dict[str, List[str]]
    validated_search_results: Dict[str, List[Dict[str, str]]]
    validation: Dict[str, Any]
    failed_subquestions: List[Dict[str, str]]

    # Organized research brief and consolidated source list from synthesizer
    brief: str

    # Final formatted markdown report with inline citations and references
    report: str

    # Overall run outcome set by the gate/loop: "", "FAILED", "PARTIAL"
    execution_status: str
    execution_error: str

    # --- Phase 2 (Critic & Revision Loop) ---
    draft: str
    critique: Dict[str, Any]
    revision_count: int
    score_history: Annotated[List[Dict[str, Any]], append_list]
    # Every draft version ever produced: [{version, author, text, chars}]
    draft_history: Annotated[List[Dict[str, Any]], append_list]
    loop_error: str

    # Runtime operational metrics (latency per node, token counts, llm_calls)
    metadata: Annotated[Dict[str, Any], merge_dicts]


def current_run_records(state: Dict[str, Any]) -> tuple:
    """
    Return ``(valid_records, foreign_records)`` for the CURRENT run.

    * valid   : status == "ok" and run_id matches the state's run_id
    * foreign : records stamped with a DIFFERENT run_id (isolation violation)
    Legacy-shaped states (no research_records) fall back to ``notes``.
    """
    rid = state.get("run_id", "")
    recs = state.get("research_records") or []
    if not recs and state.get("notes"):
        recs = [
            {"run_id": rid, "sub_question": sq, "status": "ok", "findings": list(f), "sources": (state.get("search_results") or {}).get(sq, [])}
            for sq, f in state["notes"].items()
        ]
    valid, foreign = [], []
    for r in recs:
        if rid and r.get("run_id") != rid:
            foreign.append(r)
        elif r.get("status") == "ok":
            valid.append(r)
    return valid, foreign


def new_run_state(question: str, run_id: Optional[str] = None, benchmark_id: Optional[str] = None) -> ResearchState:
    """
    Build a FRESH ResearchState for exactly one research run.
    All containers are newly allocated: nothing from a previous run can leak in.
    """
    rid = run_id or generate_run_id()
    return {
        "run_id": rid,
        "benchmark_id": benchmark_id or "",
        "question": (question or "").strip(),
        "plan": [],
        "search_results": {},
        "notes": {},
        "research_records": [],
        "validated_notes": {},
        "validated_search_results": {},
        "validation": {},
        "failed_subquestions": [],
        "brief": "",
        "report": "",
        "execution_status": "",
        "execution_error": "",
        "draft": "",
        "critique": {},
        "revision_count": 0,
        "score_history": [],
        "draft_history": [],
        "loop_error": "",
        "metadata": {"search_count": 0, "llm_calls": [], "run_id": rid},
    }
