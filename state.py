"""
State Definition for Multi-Agent Deep Research System
Architecture Reference: docs/EXPLANATIONS.md - Section 2: "The Shared State"

First Principle:
State in an agent graph acts as the blackboard communication channel.
Agents read their necessary inputs and write back their localized findings,
allowing decoupled parallel execution without point-to-point message passing.
"""

from typing import Annotated, Any, Dict, List, TypedDict


def merge_dicts(left: Dict[str, Any], right: Dict[str, Any]) -> Dict[str, Any]:
    """Reducer function to merge dictionaries from concurrent agent nodes."""
    merged = dict(left or {})
    for key, value in (right or {}).items():
        if key in merged and isinstance(merged[key], list) and isinstance(value, list):
            merged[key] = merged[key] + value
        elif key in merged and isinstance(merged[key], dict) and isinstance(value, dict):
            merged[key] = merge_dicts(merged[key], value)
        elif key in merged and isinstance(merged[key], (int, float)) and isinstance(value, (int, float)):
            # Numeric values like token count can accumulate
            if key in ("search_count", "total_tokens", "prompt_tokens", "completion_tokens"):
                merged[key] = merged[key] + value
            else:
                merged[key] = value
        else:
            merged[key] = value
    return merged


class ResearchState(TypedDict):
    """
    Central shared state passed between all nodes in the LangGraph workflow.
    """
    # The primary user query / topic
    question: str

    # The decomposed sub-questions generated by the planner
    plan: List[str]

    # Search results keyed by sub-question: {sub_question: [{title, url, snippet}, ...]}
    search_results: Annotated[Dict[str, List[Dict[str, str]]], merge_dicts]

    # Researcher findings keyed by sub-question: {sub_question: [bullet_notes_with_urls, ...]}
    notes: Annotated[Dict[str, List[str]], merge_dicts]

    # Organized research brief and consolidated source list from synthesizer
    brief: str

    # Final formatted markdown report with inline citations and references
    report: str

    # Runtime operational metrics (latency per node, token counts, search count)
    metadata: Annotated[Dict[str, Any], merge_dicts]
